#!/bin/bash
set -euo pipefail

# Regenerates the instance-type sizing table shown in
# docs/src/modules/operations/pages/services/instance-sizing.adoc.
#
# The canonical catalog lives outside this repo, in the `cli` repo at
# internal/instancetypes/instance_types.json (kept in sync there with the
# `kalix` repo's api/kalix/platform/instance_types.json). There is no
# automated cross-repo sync into akka-sdk today, so re-run this script by
# hand whenever that catalog changes, pointing it at a checkout of either
# repo:
#
#   docs/bin/generate_instance_types_table.sh \
#     ~/Development/cli/internal/instancetypes/instance_types.json
#
# Requires `jq`.

if [[ $# -ne 1 ]]; then
  echo "usage: $0 <path-to-instance_types.json>" >&2
  exit 1
fi

source_json="$1"
out_file="$(dirname "$0")/../src/modules/operations/partials/instance-types-table.adoc"

if [[ ! -f "$source_json" ]]; then
  echo "ERROR: $source_json not found" >&2
  exit 1
fi

{
  echo "// Generated by docs/bin/generate_instance_types_table.sh from"
  echo "// instance_types.json. Do not hand-edit; re-run the script instead."
  echo "// Sizing is embedded-mode only: the only runtime mode Akka services support."
  echo "[cols=\"2,1,1,1\", options=\"header\"]"
  echo "|==="
  echo "| Instance type | Shape | CPU | Memory"

  jq -r '
    def size_rank: {"x-small": 0, "small": 1, "medium": 2, "large": 3};
    .entries
    | map(select(.status == "active"))
    | map(. + {shape: (.displayName | split(".")[1]), size: (.displayName | split(".")[2])})
    | sort_by([.shape, (.size | size_rank)])
    | .[]
    | "| `" + .displayName + "`" +
      (if .platform_default then " (platform default)" else "" end) +
      " | " + .shape +
      " | " + .embedded.runtime.cpu +
      " | " + .embedded.runtime.memory
  ' "$source_json"

  echo "|==="
} > "$out_file"

echo "Wrote $out_file"
