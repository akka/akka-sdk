#!/usr/bin/env node
// Generates the permissions and roles tables of the RBAC reference pages as AsciiDoc partials.
//
// The Akka control plane serves the source documents:
//   <base>/permissions.json  permissions grouped by type and resource, each with the built-in roles that include it
//   <base>/roles.json        the built-in roles and their permissions
//
// Usage: generate-rbac-tables.mjs OUTPUT_DIR
//
// Environment:
//   RBAC_RESOURCES_URL  base URL of the documents, default https://api.kalix.dev/resources/rbac
//   RBAC_RESOURCES_DIR  directory with saved copies of the two documents, used instead of the URL

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const outputDir = process.argv[2];
if (!outputDir) {
  console.error('Usage: generate-rbac-tables.mjs OUTPUT_DIR');
  process.exit(1);
}

const baseUrl = (process.env.RBAC_RESOURCES_URL || 'https://api.kalix.dev/resources/rbac').replace(/\/$/, '');
const localDir = process.env.RBAC_RESOURCES_DIR;

async function load(name) {
  if (localDir) {
    return JSON.parse(await readFile(path.join(localDir, name), 'utf8'));
  }
  const response = await fetch(`${baseUrl}/${name}`);
  if (!response.ok) {
    throw new Error(`GET ${baseUrl}/${name} returned HTTP ${response.status}`);
  }
  return response.json();
}

// Escapes text for use inside a table cell, as inline passthrough of special characters.
function text(value) {
  const escaped = String(value ?? '')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\\/g, '\\\\')
    .replace(/\]/g, '\\]')
    .replace(/\|/g, '\\|');
  return `pass:c[${escaped}]`;
}

const code = (value) => `\`${value}\``;

function roleAnchor(roleName) {
  return 'role-' + roleName.replace(/[^a-zA-Z0-9]+/g, '-');
}

function permissionsTable(doc) {
  const lines = [
    '[.rbac-permissions, cols="3,5,2,3", options="header"]',
    '|===',
    '| Permission | Description | Granted on | Built-in roles',
  ];
  for (const type of doc.types) {
    lines.push('', `4+h| [.rbac-type]#${type.name}# ${text(type.description)}`);
    const add = (permission, prefix, grantedOn) => {
      const granted = permission.grantedOn || grantedOn;
      const roles = (permission.roles || [])
        .map((role) => `xref:reference:rbac/roles.adoc#${roleAnchor(role)}[${code(role)}]`)
        .join(' +\n');
      lines.push(
        '',
        `| ${code(`${prefix}.${permission.name}`)}`,
        `| ${text(permission.description)}`,
        `| ${granted ? code(granted) : ''}`,
        `| ${roles}`,
      );
    };
    for (const permission of type.permissions || []) {
      add(permission, type.name, type.grantedOn);
    }
    for (const resource of type.resources || []) {
      const prefix = `${type.name}.${resource.name}`;
      lines.push('', `4+h| [.rbac-resource]#${prefix}# ${text(resource.description)}`);
      for (const permission of resource.permissions) {
        add(permission, prefix, resource.grantedOn || type.grantedOn);
      }
    }
  }
  lines.push('|===', '');
  return lines.join('\n');
}

function rolesTable(doc) {
  const lines = ['[.rbac-roles, cols="3,5,4", options="header"]', '|===', '| Role | Description | Permissions'];
  for (const role of doc) {
    lines.push(
      '',
      `| anchor:${roleAnchor(role.roleName)}[]${code(role.roleName)}`,
      `| ${text(role.description)}`,
      `| ${role.permissions.map(code).join(' +\n')}`,
    );
  }
  lines.push('|===', '');
  return lines.join('\n');
}

const header = '// Generated by docs/bin/generate-rbac-tables.mjs. Do not edit.\n';

try {
  const [permissions, roles] = await Promise.all([load('permissions.json'), load('roles.json')]);
  await mkdir(outputDir, { recursive: true });
  await writeFile(path.join(outputDir, 'permissions-table.adoc'), header + permissionsTable(permissions));
  await writeFile(path.join(outputDir, 'roles-table.adoc'), header + rolesTable(roles));
} catch (error) {
  console.error(`Could not generate the RBAC tables: ${error.message}`);
  console.error('Set RBAC_RESOURCES_URL, or RBAC_RESOURCES_DIR to a directory with permissions.json and roles.json.');
  process.exit(1);
}
